#include "dazzle/dazzle.h"

//////////////////////////////////////////////////////////////////////////
dz_uint32_t dz_get_magic( void )
{
    return 'D' + ('A' << 8) + ('Z' << 16) + ('Z' << 24);
}
//////////////////////////////////////////////////////////////////////////
dz_uint32_t dz_get_version( void )
{
    return 5;
}
